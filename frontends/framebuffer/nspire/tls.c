/**
 * \file
 * TLS for the TI-Nspire's HTTPS fetcher: mbedTLS client configuration.
 *
 * Trust: the root certificates (Mozilla's, as curl publishes them) are
 * built into the program as DER (nspire_ca_certs, generated by
 * scripts/mkres.py). Parsing all of them takes long on the calculator, so
 * nothing is parsed up front: mbedTLS asks, per certificate it verifies,
 * for the roots whose subject is that certificate's issuer, and only those
 * are parsed. A user file nspire_ca.pem.tns next to the program adds roots.
 *
 * The calculator's clock is often not set; while it is before the build
 * date, certificates are not rejected for their validity dates.
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include <mbedtls/asn1.h>
#include <mbedtls/ctr_drbg.h>
#include <mbedtls/entropy.h>
#include <mbedtls/platform_time.h>
#include <mbedtls/ssl.h>
#include <mbedtls/x509_crt.h>
#include <psa/crypto.h>

#include "utils/log.h"

#include "framebuffer/nspire/nspire.h"
#include "framebuffer/nspire/sys.h"

/* generated: the built-in roots */
struct nspire_ca_cert {
	const uint8_t *der;
	uint32_t len;
};
extern const struct nspire_ca_cert nspire_ca_certs[];
extern const unsigned nspire_ca_cert_count;

#ifndef NSPIRE_BUILD_EPOCH
#define NSPIRE_BUILD_EPOCH 1790000000u
#endif

struct ca_index {
	const uint8_t *der;
	size_t len;
	const uint8_t *subject;	/* raw DER of the subject Name */
	size_t subject_len;
};

static bool ready, broken;
static mbedtls_entropy_context entropy;
static mbedtls_ctr_drbg_context drbg;
static mbedtls_ssl_config conf_verify, conf_noverify;
static struct ca_index *cas;
static unsigned ca_count;
static mbedtls_x509_crt user_cas;
static bool have_user_cas;

#ifdef _TINSPIRE
/* MBEDTLS_ENTROPY_HARDWARE_ALT: timer jitter and whatever else moves */
int mbedtls_hardware_poll(void *data, unsigned char *output, size_t len, size_t *olen);
int mbedtls_hardware_poll(void *data, unsigned char *output, size_t len, size_t *olen)
{
	size_t i;
	uint32_t x = 0;

	(void)data;
	for (i = 0; i < len; i++) {
		volatile int spin;
		int n = (int)(nspire_us() & 7u) + 3;
		for (spin = 0; spin < n; spin++)
			;
		x = x * 2654435761u + nspire_entropy() + (uint32_t)nspire_us();
		output[i] = (unsigned char)(x ^ (x >> 13) ^ (x >> 24));
	}
	*olen = len;
	return 0;
}
#endif

#ifdef MBEDTLS_PLATFORM_MS_TIME_ALT
mbedtls_ms_time_t mbedtls_ms_time(void)
{
	return (mbedtls_ms_time_t)(nspire_us() / 1000u);
}
#endif

/* Find the subject Name of a certificate without parsing all of it. */
static bool find_subject(const uint8_t *der, size_t len, const uint8_t **subject,
			 size_t *subject_len)
{
	unsigned char *p = (unsigned char *)der;
	const unsigned char *end = der + len;
	size_t l;

	if (mbedtls_asn1_get_tag(&p, end, &l, MBEDTLS_ASN1_CONSTRUCTED | MBEDTLS_ASN1_SEQUENCE) != 0)
		return false;			/* Certificate */
	if (mbedtls_asn1_get_tag(&p, end, &l, MBEDTLS_ASN1_CONSTRUCTED | MBEDTLS_ASN1_SEQUENCE) != 0)
		return false;			/* TBSCertificate */
	end = p + l;
	/* [0] version, optional */
	if (p < end && *p == (MBEDTLS_ASN1_CONTEXT_SPECIFIC | MBEDTLS_ASN1_CONSTRUCTED | 0)) {
		if (mbedtls_asn1_get_tag(&p, end, &l, *p) != 0)
			return false;
		p += l;
	}
	/* serial, signature algorithm, issuer, validity */
	if (mbedtls_asn1_get_tag(&p, end, &l, MBEDTLS_ASN1_INTEGER) != 0)
		return false;
	p += l;
	if (mbedtls_asn1_get_tag(&p, end, &l, MBEDTLS_ASN1_CONSTRUCTED | MBEDTLS_ASN1_SEQUENCE) != 0)
		return false;
	p += l;
	if (mbedtls_asn1_get_tag(&p, end, &l, MBEDTLS_ASN1_CONSTRUCTED | MBEDTLS_ASN1_SEQUENCE) != 0)
		return false;
	p += l;
	if (mbedtls_asn1_get_tag(&p, end, &l, MBEDTLS_ASN1_CONSTRUCTED | MBEDTLS_ASN1_SEQUENCE) != 0)
		return false;
	p += l;
	/* subject, with its header: issuer_raw in mbedTLS is the same */
	{
		unsigned char *start = p;
		if (mbedtls_asn1_get_tag(&p, end, &l, MBEDTLS_ASN1_CONSTRUCTED | MBEDTLS_ASN1_SEQUENCE) != 0)
			return false;
		*subject = start;
		*subject_len = (size_t)(p - start) + l;
	}
	return true;
}

static void index_cas(void)
{
	unsigned i;

	cas = calloc(nspire_ca_cert_count ? nspire_ca_cert_count : 1, sizeof(*cas));
	if (cas == NULL)
		return;
	for (i = 0; i < nspire_ca_cert_count; i++) {
		struct ca_index *c = &cas[ca_count];
		c->der = nspire_ca_certs[i].der;
		c->len = nspire_ca_certs[i].len;
		if (find_subject(c->der, c->len, &c->subject, &c->subject_len))
			ca_count++;
	}
	NSLOG(netsurf, INFO, "tls: %u built-in roots", ca_count);
}

static bool same_name(const mbedtls_x509_buf *raw, const uint8_t *name, size_t len)
{
	/* mbedTLS' issuer_raw starts at the Name's SEQUENCE tag */
	return raw->len == len && memcmp(raw->p, name, len) == 0;
}

/* MBEDTLS_X509_TRUSTED_CERTIFICATE_CALLBACK */
static int ca_callback(void *ctx, mbedtls_x509_crt const *child, mbedtls_x509_crt **candidates)
{
	mbedtls_x509_crt *list = NULL;
	const mbedtls_x509_crt *u;
	unsigned i;

	(void)ctx;
	for (i = 0; i < ca_count; i++) {
		if (!same_name(&child->issuer_raw, cas[i].subject, cas[i].subject_len))
			continue;
		if (list == NULL) {
			list = malloc(sizeof(*list));
			if (list == NULL)
				break;
			mbedtls_x509_crt_init(list);
		}
		if (mbedtls_x509_crt_parse_der_nocopy(list, cas[i].der, cas[i].len) != 0)
			NSLOG(netsurf, INFO, "tls: built-in root %u does not parse", i);
	}
	if (have_user_cas) {
		for (u = &user_cas; u != NULL && u->raw.p != NULL; u = u->next) {
			if (child->issuer_raw.len != u->subject_raw.len ||
			    memcmp(child->issuer_raw.p, u->subject_raw.p, u->subject_raw.len) != 0)
				continue;
			if (list == NULL) {
				list = malloc(sizeof(*list));
				if (list == NULL)
					break;
				mbedtls_x509_crt_init(list);
			}
			mbedtls_x509_crt_parse_der(list, u->raw.p, u->raw.len);
		}
	}
	if (list != NULL && list->raw.p == NULL) {
		mbedtls_x509_crt_free(list);
		free(list);
		list = NULL;
	}
	*candidates = list;
	return 0;
}

static int verify_callback(void *ctx, mbedtls_x509_crt *crt, int depth, uint32_t *flags)
{
	(void)ctx;
	(void)crt;
	(void)depth;
	if (nspire_unix_time() < NSPIRE_BUILD_EPOCH)
		*flags &= ~(uint32_t)(MBEDTLS_X509_BADCERT_EXPIRED | MBEDTLS_X509_BADCERT_FUTURE);
	return 0;
}

static void load_user_cas(void)
{
	char path[300];

	mbedtls_x509_crt_init(&user_cas);
	snprintf(path, sizeof(path), "%s/nspire_ca.pem.tns", nspire_app_dir());
	{
		FILE *f = fopen(path, "rb");
		long n;
		unsigned char *buf;
		if (f == NULL)
			return;
		fseek(f, 0, SEEK_END);
		n = ftell(f);
		fseek(f, 0, SEEK_SET);
		buf = malloc((size_t)n + 1);
		if (buf != NULL && fread(buf, 1, (size_t)n, f) == (size_t)n) {
			buf[n] = '\0';
			if (mbedtls_x509_crt_parse(&user_cas, buf, (size_t)n + 1) >= 0 &&
			    user_cas.raw.p != NULL)
				have_user_cas = true;
		}
		free(buf);
		fclose(f);
	}
	if (have_user_cas)
		nspire_log("tls: roots added from %s\n", path);
}

static int setup_conf(mbedtls_ssl_config *conf, bool verify)
{
	int ret;

	mbedtls_ssl_config_init(conf);
	ret = mbedtls_ssl_config_defaults(conf, MBEDTLS_SSL_IS_CLIENT,
					  MBEDTLS_SSL_TRANSPORT_STREAM,
					  MBEDTLS_SSL_PRESET_DEFAULT);
	if (ret != 0)
		return ret;
	mbedtls_ssl_conf_rng(conf, mbedtls_ctr_drbg_random, &drbg);
	mbedtls_ssl_conf_authmode(conf, verify ? MBEDTLS_SSL_VERIFY_REQUIRED :
				  MBEDTLS_SSL_VERIFY_NONE);
	mbedtls_ssl_conf_ca_cb(conf, ca_callback, NULL);
	mbedtls_ssl_conf_verify(conf, verify_callback, NULL);
	return 0;
}

const struct mbedtls_ssl_config *nspire_tls_config(bool verify)
{
	static const char pers[] = "netsurf-nspire";
	int ret;

	if (broken)
		return NULL;
	if (ready)
		return verify ? &conf_verify : &conf_noverify;

	if (psa_crypto_init() != PSA_SUCCESS) {
		nspire_log("tls: psa_crypto_init failed\n");
		broken = true;
		return NULL;
	}
	mbedtls_entropy_init(&entropy);
	mbedtls_ctr_drbg_init(&drbg);
	ret = mbedtls_ctr_drbg_seed(&drbg, mbedtls_entropy_func, &entropy,
				    (const unsigned char *)pers, sizeof(pers) - 1);
	if (ret != 0) {
		nspire_log("tls: random generator: -0x%04x\n", (unsigned)-ret);
		broken = true;
		return NULL;
	}
	index_cas();
	load_user_cas();
	if (setup_conf(&conf_verify, true) != 0 || setup_conf(&conf_noverify, false) != 0) {
		nspire_log("tls: configuration failed\n");
		broken = true;
		return NULL;
	}
	ready = true;
	return verify ? &conf_verify : &conf_noverify;
}

void nspire_tls_finalise(void)
{
	if (ready) {
		mbedtls_ssl_config_free(&conf_verify);
		mbedtls_ssl_config_free(&conf_noverify);
		mbedtls_ctr_drbg_free(&drbg);
		mbedtls_entropy_free(&entropy);
		mbedtls_x509_crt_free(&user_cas);
		free(cas);
		cas = NULL;
		ca_count = 0;
		ready = false;
	}
}
