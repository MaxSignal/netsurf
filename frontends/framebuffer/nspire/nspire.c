/* generated by scripts/mkres.py */
struct nspire_resource {
	const char *name;
	const uint8_t *data;
	size_t len;
};
extern const struct nspire_resource nspire_resources[];

#ifndef NSPIRE_VERSION
#define NSPIRE_VERSION "dev"
#endif

static char choices_path[300];
static char urls_path[300];
static char *verbose_argv[64];
static char verbose_log_path[300];

static const struct nspire_resource *find_resource(const char *name)
{
	const struct nspire_resource *r;

	for (r = nspire_resources; r->name != NULL; r++)
		if (strcmp(r->name, name) == 0)
			return r;
	return NULL;
}

void nspire_early_init(int *argc, char ***argv)
{
	char flag[300];
	struct stat st;
	int i;

	nspire_sys_init(*argc, *argv);
	nspire_log("NetSurf for TI-Nspire %s, built %s %s\n", NSPIRE_VERSION, __DATE__, __TIME__);
	snprintf(choices_path, sizeof(choices_path), "%s/netsurf_choices.tns", nspire_app_dir());
	snprintf(urls_path, sizeof(urls_path), "%s/netsurf_urls.tns", nspire_app_dir());

	/* NetSurf's own log, on request */
	snprintf(flag, sizeof(flag), "%s/netsurf_verbose.tns", nspire_app_dir());
	if (stat(flag, &st) == 0 && *argc + 2 < (int)(sizeof(verbose_argv) / sizeof(verbose_argv[0]))) {
		snprintf(verbose_log_path, sizeof(verbose_log_path),
			 "%s/netsurf_verbose_log.txt.tns", nspire_app_dir());
		verbose_argv[0] = (*argv)[0];
		verbose_argv[1] = (char *)"-V";
		verbose_argv[2] = verbose_log_path;
		for (i = 1; i < *argc; i++)
			verbose_argv[i + 2] = (*argv)[i];
		verbose_argv[*argc + 2] = NULL;
		*argc += 2;
		*argv = verbose_argv;
	}
}

nserror nspire_messages_init(void)
{
	const struct nspire_resource *r = find_resource("Messages");

	if (r == NULL)
		return NSERROR_NOT_FOUND;
	return messages_add_from_inline(r->data, r->len);
}

nserror nspire_url_from_text(const char *text, struct nsurl **url)
{
	static const char *const schemes[] = {
		"http:", "https:", "about:", "resource:", "file:", "data:", NULL
	};
	const char *p;
	char *with_scheme;
	size_t host_len;
	bool hostlike = true, dotted = false;
	nserror err;
	int i;

	while (*text == ' ')
		text++;
	for (i = 0; schemes[i] != NULL; i++)
		if (strncasecmp(text, schemes[i], strlen(schemes[i])) == 0)
			return nsurl_create(text, url);
	if (strstr(text, "://") != NULL)
		return nsurl_create(text, url);

	/* a host name, perhaps with a port and a path? */
	host_len = strcspn(text, ":/?#");
	if (host_len == 0)
		hostlike = false;
	for (p = text; *p != '\0' && hostlike; p++) {
		if (*p == ' ')
			hostlike = false;
	}
	for (p = text; p < text + host_len; p++) {
		if (*p == '.')
			dotted = true;
		else if (!((*p >= 'a' && *p <= 'z') || (*p >= 'A' && *p <= 'Z') ||
			   (*p >= '0' && *p <= '9') || *p == '-' || (unsigned char)*p >= 0x80))
			hostlike = false;
	}
	if (hostlike && (dotted || text[host_len] == ':' || text[host_len] == '/' ||
			 (host_len == 2 && strncasecmp(text, "pc", 2) == 0) ||
			 (host_len == 9 && strncasecmp(text, "localhost", 9) == 0))) {
		/* plain http for the computer at the end of the cable and for
		 * addresses; https for the rest of the web */
		bool local = (host_len == 2 && strncasecmp(text, "pc", 2) == 0) ||
			strspn(text, "0123456789.") == host_len;
		with_scheme = malloc(strlen(text) + 9);
		if (with_scheme == NULL)
			return NSERROR_NOMEM;
		sprintf(with_scheme, "%s%s", local ? "http://" : "https://", text);
		err = nsurl_create(with_scheme, url);
		free(with_scheme);
		if (err == NSERROR_OK)
			return NSERROR_OK;
	}
	return search_web_omni(text, SEARCH_WEB_OMNI_SEARCHONLY, url);
}

/* Search engines that give a plain browser plain result pages (the
 * DuckDuckGo HTML page NetSurf uses elsewhere answers it with an image
 * CAPTCHA). The first one is used unless Choices names another with
 * search_web_provider. NetSurf's format: name|host|URL (%s: the
 * words)|icon URL| per line, no comments. */
static const char default_search_engines[] =
	"Bing|www.bing.com|https://www.bing.com/search?q=%s|https://www.bing.com/favicon.ico|\n"
	"Wikipedia|en.m.wikipedia.org|https://en.m.wikipedia.org/w/index.php?search=%s|https://en.m.wikipedia.org/favicon.ico|\n"
	"Wiby|wiby.me|https://wiby.me/?q=%s|https://wiby.me/favicon.ico|\n"
	"DuckDuckGo Lite|lite.duckduckgo.com|https://lite.duckduckgo.com/lite/?q=%s|https://duckduckgo.com/favicon.ico|\n"
	"Google|www.google.com|https://www.google.com/search?q=%s|https://www.google.com/favicon.ico|\n";

static void search_engines_init(void)
{
	char path[300];
	struct stat st;
	FILE *f;

	snprintf(path, sizeof(path), "%s/netsurf_search.tns", nspire_app_dir());
	if (stat(path, &st) != 0) {
		f = fopen(path, "w");
		if (f != NULL) {
			fputs(default_search_engines, f);
			fclose(f);
		}
	}
	if (search_web_init(path) != NSERROR_OK) {
		nspire_log("search: cannot read %s\n", path);
		return;
	}
	if (nsoption_charp(search_web_provider) != NULL &&
	    nsoption_charp(search_web_provider)[0] != '\0')
		search_web_select_provider(nsoption_charp(search_web_provider));
}

const char *nspire_app_dir_respath(void)
{
	return nspire_app_dir();
}

const char *nspire_choices_path(void)
{
	return choices_path;
}

nserror nspire_init(void)
{
	nserror err;
	char path[300];

	err = nspire_fetch_http_register();
	if (err != NSERROR_OK) {
		nspire_log("http fetcher: %s\n", messages_get_errorcode(err));
		return err;
	}

	urldb_load(urls_path);
	snprintf(path, sizeof(path), "%s/netsurf_cookies.tns", nspire_app_dir());
	nsoption_set_charp(cookie_file, strdup(path));
	nsoption_set_charp(cookie_jar, strdup(path));

	search_engines_init();
	nspire_net_start();
	return NSERROR_OK;
}

void nspire_finalise(void)
{
	urldb_save(urls_path);
	nspire_net_stop();
}

void nspire_late_finalise(void)
{
	nspire_log("exit, heap peak %lu bytes\n", (unsigned long)nspire_heap_peak());
	nspire_sys_fini();
}

nserror nspire_get_resource_data(const char *path, const uint8_t **data, size_t *len)
{
	const struct nspire_resource *r;

	if (strcmp(path, "favicon.ico") == 0 || strcmp(path, "default.ico") == 0)
		path = "favicon.png";
	r = find_resource(path);
	if (r == NULL)
		return NSERROR_NOT_FOUND;
	*data = r->data;
	*len = r->len;
	return NSERROR_OK;
}

nserror nspire_release_resource_data(const uint8_t *data)
{
	(void)data;
	return NSERROR_OK;
}
