#!/usr/bin/env python3
"""Builds the TI-Nspire frontend's built-in data as C source.

Files on the calculator have to end in .tns, and a single program file is
the easy thing to copy, so the resources NetSurf reads (style sheets, pages,
icons, the Messages) and the root certificates go into the program.

  mkres.py <out.c> <ca-bundle.pem> <name>=<file> ...

The names are resource: paths ("default.css"). The CA bundle is a PEM file;
its certificates become DER.
"""
import base64
import re
import sys


def c_array(name, data):
    out = ["static const uint8_t %s[%d] = {" % (name, len(data) + 1)]
    for i in range(0, len(data), 20):
        out.append("  " + ",".join(str(b) for b in data[i:i + 20]) + ",")
    out.append("  0 };")  # NUL after the data: some readers want a string
    return "\n".join(out)


def main():
    out_path, ca_path = sys.argv[1], sys.argv[2]
    resources = []
    for arg in sys.argv[3:]:
        name, path = arg.split("=", 1)
        with open(path, "rb") as f:
            resources.append((name, f.read()))

    with open(ca_path, "r", encoding="ascii", errors="replace") as f:
        pem = f.read()
    ders = [base64.b64decode("".join(m.split()))
            for m in re.findall(r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----",
                                pem, re.S)]

    lines = ["/* generated by mkres.py: do not edit */",
             "#include <stddef.h>", "#include <stdint.h>", "#include <string.h>", ""]
    for i, (name, data) in enumerate(resources):
        lines.append("/* %s */" % name)
        lines.append(c_array("res_%d" % i, data))
    lines.append("")
    lines.append("struct nspire_resource { const char *name; const uint8_t *data; size_t len; };")
    lines.append("const struct nspire_resource nspire_resources[] = {")
    for i, (name, data) in enumerate(resources):
        lines.append('  { "%s", res_%d, %d },' % (name, i, len(data)))
    lines.append("  { NULL, NULL, 0 } };")
    lines.append("")
    for i, der in enumerate(ders):
        lines.append(c_array("ca_%d" % i, der))
    lines.append("struct nspire_ca_cert { const uint8_t *der; uint32_t len; };")
    lines.append("const struct nspire_ca_cert nspire_ca_certs[] = {")
    for i, der in enumerate(ders):
        lines.append("  { ca_%d, %d }," % (i, len(der)))
    lines.append("  { NULL, 0 } };")
    lines.append("const unsigned nspire_ca_cert_count = %d;" % len(ders))
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
